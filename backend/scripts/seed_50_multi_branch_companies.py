async def seed_50_companies() -> None:
    async with AsyncSessionLocal() as db:
        # Load department map
        depts = (await db.execute(select(Department))).scalars().all()
        dept_by_code = {d.code.upper().strip(): d.id for d in depts if d.code}

        # Check existing companies
        existing_companies = (await db.execute(select(Company))).scalars().all()
        existing_company_names = {c.name.strip().lower() for c in existing_companies}

        deadline = datetime.now(timezone.utc) + timedelta(days=90)
        created_count = 0
        skipped_count = 0

        for item in COMPANIES_DATA:
            comp_name = item["name"].strip()
            if comp_name.lower() in existing_company_names:
                skipped_count += 1
                continue

            # Create Company
            comp = Company(
                name=comp_name,
                industry=item["industry"],
                description=f"{comp_name} is a leading industry pioneer in {item['industry']}, offering technical career paths and development programs.",
                website=item["website"],
                location=item["location"],
                company_size=item["size"],
                contact_email=item["email"],
                contact_phone="+91-11-4000-8800",
                is_verified=True,
                is_active=True,
                institution_id=1,
            )
            db.add(comp)
            await db.flush()
            existing_company_names.add(comp_name.lower())

            # Create associated Job
            dept_id = dept_by_code.get(item["dept_code"].upper().strip())
            job = Job(
                company_id=comp.id,
                institution_id=1,
                created_by_user_id=7,  # admin user
                title=item["job_title"],
                description=(
                    f"{comp_name} invites applications for {item['job_title']}. "
                    f"Selected engineers will collaborate on industrial projects, design deliverables, and high-impact operations. "
                    f"Applicants should possess strong foundations in {item['dept_code']} core principles."
                ),
                employment_type=EmploymentType.FULL_TIME,
                work_mode=WorkMode.ON_SITE if "Offshore" in item["location"] or "Plant" in item["job_title"] else WorkMode.HYBRID,
                location=item["location"],
                salary_range=item["salary_range"],
                ctc_lpa=item["ctc_lpa"],
                min_cgpa=item["min_cgpa"],
                target_graduation_year=2026,
                max_active_backlogs=0,
                max_total_backlogs=2,
                application_deadline=deadline,
                status=JobStatus.PUBLISHED,
                is_active=True,
            )
            db.add(job)
            await db.flush()

            # Attach eligible department
            if dept_id:
                elig_dept = JobEligibleDepartment(
                    job_id=job.id,
                    department_id=dept_id,
                )
                db.add(elig_dept)

            # Attach skills
            for skill_name, is_mandatory in item["skills"]:
                js = JobSkill(
                    job_id=job.id,
                    skill_name=skill_name,
                    is_mandatory=is_mandatory,
                )
                db.add(js)

            created_count += 1

        await db.commit()
        print(f"Successfully created {created_count} new companies and published jobs! (Skipped existing: {skipped_count})")


if __name__ == "__main__":
    asyncio.run(seed_50_companies())
