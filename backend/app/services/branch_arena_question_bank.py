def resolve_department_arena_categories(dept_code: str, dept_name: str) -> List[ArenaCategory]:
    """Resolve active arena categories for a student's verified department.
    
    Returns:
        Common Placement Categories (Aptitude, Reasoning, Verbal, HR) + Branch Core Categories.
        CS subjects are strictly included ONLY if department is CS/IT!
    """
    code = (dept_code or "").upper().strip()
    name = (dept_name or "").lower().strip()

    branch_cats: List[ArenaCategory] = []
    if code in DEPARTMENT_ARENA_CATEGORIES:
        branch_cats = DEPARTMENT_ARENA_CATEGORIES[code]
    elif "civil" in name:
        branch_cats = DEPARTMENT_ARENA_CATEGORIES["CIVIL"]
    elif "mech" in name:
        branch_cats = DEPARTMENT_ARENA_CATEGORIES["MECH"]
    elif "electr" in name and "comm" not in name and "tele" not in name:
        branch_cats = DEPARTMENT_ARENA_CATEGORIES["EEE"]
    elif "comm" in name or "ece" in name or "telecom" in name or "electron" in name:
        branch_cats = DEPARTMENT_ARENA_CATEGORIES["ECE"]
    elif "chem" in name:
        branch_cats = DEPARTMENT_ARENA_CATEGORIES["CHEM"]
    elif "mining" in name:
        branch_cats = DEPARTMENT_ARENA_CATEGORIES["MINE"]
    elif "petro" in name or "oil" in name:
        branch_cats = DEPARTMENT_ARENA_CATEGORIES["PETRO"]
    elif "prod" in name or "industr" in name or "pie" in name:
        branch_cats = DEPARTMENT_ARENA_CATEGORIES["PIE"]
    elif "struct" in name:
        branch_cats = DEPARTMENT_ARENA_CATEGORIES["STRUCT"]
    elif "arch" in name or "plan" in name:
        branch_cats = DEPARTMENT_ARENA_CATEGORIES["ARCH_PLAN"]
    elif "comp" in name or "info" in name or "soft" in name or "data" in name or "ai" in name:
        branch_cats = CS_ARENA_CATEGORIES
    else:
        # Default fallback to common placement only
        branch_cats = []

    # Final result: Common Aptitude & Reasoning + Official Branch Core
    res = list(COMMON_ARENA_CATEGORIES)
    for c in branch_cats:
        if c not in res:
            res.append(c)
    return res


