from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field
from app.schemas.ai import AIUsageMetadata


class ChatMessage(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    role: str = Field(..., description="Role of the sender: 'user' or 'assistant'")
    content: str = Field(..., description="Message text content")


class CareerAssistantChatRequest(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    message: str = Field(
        ...,
        min_length=1,
        max_length=1500,
        description="Student career inquiry, question, or roadmap request",
    )
    job_id: Optional[int] = Field(
        None,
        description="Optional target job ID to ground advice in specific job requirements",
    )
    conversation_history: List[ChatMessage] = Field(
        default_factory=list,
        description="Recent conversation history within the current session (max 10)",
    )


class CareerAdviceStructuredOutput(BaseModel):
    """Normalized structured career guidance generated by the AI provider."""
    model_config = ConfigDict(from_attributes=True)

    advice_type: str = Field(
        ...,
        description="Type: skill_gap_analysis, eligibility_explanation, score_interpretation, learning_roadmap, placement_preparation, general_guidance",
    )
    answer: str = Field(
        ...,
        description="Comprehensive, factual, objective markdown answer to the student",
    )
    key_points: List[str] = Field(
        default_factory=list,
        description="Core bullet points or diagnostic findings",
    )
    suggested_next_actions: List[str] = Field(
        default_factory=list,
        description="Actionable 3-5 concrete steps the student should take next",
    )
    relevant_skills_to_acquire: List[str] = Field(
        default_factory=list,
        description="Specific technical or professional skills to prioritize",
    )
    limitations_or_missing_context: Optional[str] = Field(
        None,
        description="Notice if guidance is restricted due to incomplete profile or unstated information",
    )
    disclaimer: str = Field(
        default="AI career guidance is advisory. Placement eligibility cutoffs and selection decisions are governed strictly by institutional and recruiter policies.",
        description="Mandatory compliance disclaimer",
    )


class CareerContextSummary(BaseModel):
    """Sanitized student and target job context provided to the assistant."""
    model_config = ConfigDict(from_attributes=True)

    student_id: int
    department_name: Optional[str] = None
    graduation_year: Optional[int] = None
    cgpa: Optional[float] = None
    active_backlogs: Optional[int] = None
    skills_count: int = 0
    projects_count: int = 0
    experiences_count: int = 0
    certifications_count: int = 0
    is_profile_complete: bool = True
    missing_sections: List[str] = Field(default_factory=list)

    # Job context (when applicable)
    job_id: Optional[int] = None
    job_title: Optional[str] = None
    company_name: Optional[str] = None
    is_eligible: Optional[bool] = None
    compatibility_score: Optional[float] = None
    matched_skills: List[str] = Field(default_factory=list)
    missing_mandatory_skills: List[str] = Field(default_factory=list)


class CareerAssistantResponse(BaseModel):
    """Envelope returned by the Career Assistant chat API endpoint."""
    model_config = ConfigDict(from_attributes=True)

    success: bool = True
    data: CareerAdviceStructuredOutput
    context_summary: CareerContextSummary
    usage: Optional[AIUsageMetadata] = None

    @property
    def context(self) -> CareerContextSummary:
        return self.context_summary

    @property
    def guidance(self) -> CareerAdviceStructuredOutput:
        return self.data


class CareerPromptSuggestion(BaseModel):
    model_config = ConfigDict(from_attributes=True)

    id: str
    category: str
    title: str
    prompt: str
    requires_job_context: bool = False

    @property
    def prompt_text(self) -> str:
        return self.prompt

