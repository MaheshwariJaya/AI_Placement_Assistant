"""Pydantic schemas for TASK 10: Candidate Comparison & Hiring Insights.

Provides side-by-side comparison dimensions, skill matrix mapping,
deterministic compatibility snapshots, evidence-grounded AI hiring insights,
and saved comparison sessions.
"""
from datetime import datetime
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field

from app.models.placement import ApplicationStatus
from app.schemas.candidate_evaluation import (
    CandidateAcademicInfo,
    CandidateCertificationItem,
    CandidateExperienceItem,
    CandidateProjectItem,
    CandidateResumeSummary,
    CandidateSkillItem,
)
from app.schemas.intelligence import ScoreBreakdown


class CandidateComparisonItem(BaseModel):
    """Full side-by-side comparative representation of an individual candidate application."""
    model_config = ConfigDict(from_attributes=True)

    application_id: int
    student_id: int
    user_id: int
    candidate_name: str
    roll_number: str
    email: str
    department: str
    graduation_year: int
    current_status: ApplicationStatus
    applied_at: datetime

    # Academic & Eligibility
    is_eligible: bool
    eligibility_reasons: List[str] = Field(default_factory=list)
    academics: CandidateAcademicInfo

    # Compatibility Scores
    compatibility_score_at_application: float
    current_compatibility_score: float
    score_breakdown: ScoreBreakdown

    # Skill Coverage
    mandatory_skills_coverage: Dict[str, Any]
    preferred_skills_coverage: Dict[str, Any]
    skills: List[CandidateSkillItem] = Field(default_factory=list)

    # Practical Depth & Portfolio
    projects: List[CandidateProjectItem] = Field(default_factory=list)
    total_projects_count: int = 0
    experiences: List[CandidateExperienceItem] = Field(default_factory=list)
    total_experience_months: int = 0
    certifications: List[CandidateCertificationItem] = Field(default_factory=list)

    # Resume & Evaluations
    resume: Optional[CandidateResumeSummary] = None
    interviews_count: int = 0
    evaluations_count: int = 0
    average_rating: Optional[float] = None
    latest_recommendation: Optional[str] = None
    notes_count: int = 0


class SkillMatrixRow(BaseModel):
    """Mapping of a single required or observed skill across all compared candidates."""
    skill_name: str
    is_mandatory: bool
    candidate_coverage: Dict[str, bool] = Field(
        ...,
        description="Map of candidate application_id (as str) to boolean coverage",
    )


class CandidateComparisonAISummary(BaseModel):
    """Evidence-grounded hiring synthesis generated by AI provider."""
    shared_strengths: List[str] = Field(default_factory=list)
    candidate_strengths: Dict[str, List[str]] = Field(default_factory=dict)
    missing_requirements: Dict[str, List[str]] = Field(default_factory=dict)
    project_differences: List[str] = Field(default_factory=list)
    recommended_interview_focus: Dict[str, List[str]] = Field(default_factory=dict)
    evidence_grounding_notes: str


class CandidateComparisonResponse(BaseModel):
    """Complete side-by-side comparison payload for recruiters."""
    job_id: int
    job_title: str
    company_id: int
    company_name: str
    required_mandatory_skills: List[str] = Field(default_factory=list)
    required_preferred_skills: List[str] = Field(default_factory=list)
    candidates: List[CandidateComparisonItem] = Field(default_factory=list)
    skill_matrix: List[SkillMatrixRow] = Field(default_factory=list)
    rankings: Dict[str, List[int]] = Field(default_factory=dict)
    highlights: Dict[str, Any] = Field(default_factory=dict)
    ai_insights: Optional[CandidateComparisonAISummary] = None
    comparison_timestamp: datetime = Field(default_factory=datetime.utcnow)


class CandidateComparisonRequest(BaseModel):
    """Payload to trigger live side-by-side comparison of 2-5 candidate applications."""
    job_id: int = Field(..., description="Target job posting ID")
    application_ids: List[int] = Field(
        ...,
        min_length=2,
        max_length=5,
        description="List of 2 to 5 application IDs belonging to target job posting",
    )
    generate_ai_insights: bool = Field(
        False,
        description="Whether to generate evidence-grounded AI comparison insights",
    )


class ComparisonSessionCreateRequest(BaseModel):
    """Save a recruiter comparison session for a specific job."""
    job_id: int = Field(..., description="Target job posting ID")
    title: str = Field(..., min_length=3, max_length=200, description="Session name / title")
    application_ids: List[int] = Field(..., min_length=2, max_length=5)
    notes: Optional[str] = Field(None, max_length=4000, description="Internal recruiter notes")
    include_ai_insights: bool = Field(False, description="Generate and cache AI insights")


class ComparisonSessionUpdateRequest(BaseModel):
    """Update title or notes of a saved comparison session."""
    title: Optional[str] = Field(None, min_length=3, max_length=200)
    notes: Optional[str] = Field(None, max_length=4000)


class ComparisonSessionResponse(BaseModel):
    """Representation of a saved comparison session."""
    model_config = ConfigDict(from_attributes=True)

    id: int
    company_id: int
    job_id: int
    job_title: str
    title: str
    application_ids: List[int]
    notes: Optional[str] = None
    ai_summary: Optional[Dict[str, Any]] = None
    created_by_user_id: int
    created_by_name: str
    created_at: datetime
    updated_at: datetime


class ComparisonSessionListResponse(BaseModel):
    """List of saved comparison sessions for a job/company."""
    items: List[ComparisonSessionResponse]
    total: int

